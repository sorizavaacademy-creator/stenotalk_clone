-- ── 1인당 AI 면접 횟수 ──
create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  interview_id text not null,
  used_on date not null default ((now() at time zone 'Asia/Seoul')::date),   -- 한국 시간 날짜 (하루 횟수 기준)
  used_at timestamptz not null default now()
);
create unique index if not exists ai_usage_user_interview_uq on public.ai_usage (user_id, interview_id);
create index if not exists ai_usage_user_day_idx on public.ai_usage (user_id, used_on);
create index if not exists ai_usage_used_at_idx on public.ai_usage (used_at desc);
alter table public.ai_usage enable row level security;
-- 쓰기는 ai_usage_try()로만 (본인이 직접 줄을 넣거나 지우지 못함)
drop policy if exists "ai_usage: 본인 읽기" on public.ai_usage;
create policy "ai_usage: 본인 읽기" on public.ai_usage for select to authenticated using (user_id = auth.uid());
drop policy if exists "ai_usage: 관리자 읽기" on public.ai_usage;
create policy "ai_usage: 관리자 읽기" on public.ai_usage for select to authenticated using (public.is_admin());

-- 한도 계산 (안에서만 씀). 한도 = app_settings.ai_limits {daily, total}, 없거나 0이면 하루 10회·전체 120회 (앱 화면 기본값과 같음)
--   전체 한도에는 profiles.ai_bonus(관리자가 더 준 횟수)를 더함. 관리자는 한도 없음
create or replace function public.ai_usage_calc(p_user uuid)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_admin boolean; v_bonus int; v_set jsonb; v_daily int; v_total int; v_today int; v_all int;
begin
  select coalesce(p.is_admin and p.status <> '이용 중지', false), coalesce(p.ai_bonus, 0) into v_admin, v_bonus
    from public.profiles p where p.id = p_user;
  if coalesce(v_admin, false) then return jsonb_build_object('allowed', true, 'admin', true); end if;
  select value into v_set from public.app_settings where key = 'ai_limits';
  v_daily := coalesce(nullif((v_set->>'daily')::numeric::int, 0), 10);
  v_total := coalesce(nullif((v_set->>'total')::numeric::int, 0), 120) + greatest(coalesce(v_bonus, 0), 0);
  select count(*) filter (where used_on = (now() at time zone 'Asia/Seoul')::date), count(*)
    into v_today, v_all from public.ai_usage where user_id = p_user;
  return jsonb_build_object(
    'allowed', v_today < v_daily and v_all < v_total,
    'admin', false,
    'reason', case when v_today >= v_daily then 'daily' when v_all >= v_total then 'total' end,
    'used_today', v_today, 'used_total', v_all,
    'daily_limit', v_daily, 'total_limit', v_total,
    'daily_left', greatest(v_daily - v_today, 0), 'total_left', greatest(v_total - v_all, 0));
end $$;
revoke all on function public.ai_usage_calc(uuid) from public, anon, authenticated;

-- 서버 함수가 AI를 부르기 전에 부름. 이번 면접이 처음이면 1회 세고, 이미 센 면접이면 그냥 통과
--   돌려주는 값: {allowed, admin, reason('daily'|'total'), counted, used_today, used_total, daily_limit, total_limit, daily_left, total_left}
--   allowed=false면 서버 함수가 'limit'(429)으로 거절 → 앱은 기본 꼬리질문·기본 채점으로 계속
create or replace function public.ai_usage_try(p_interview_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid(); v_iid text := left(trim(coalesce(p_interview_id, '')), 100); st jsonb;
begin
  if v_uid is null then return jsonb_build_object('allowed', false, 'reason', 'login'); end if;
  if v_iid = '' then return public.ai_usage_calc(v_uid); end if;
  perform pg_advisory_xact_lock(hashtext('ai_usage:' || v_uid::text));   -- 같은 사람이 동시에 불러도 한 번씩만 셈
  if exists (select 1 from public.ai_usage where user_id = v_uid and interview_id = v_iid) then
    return public.ai_usage_calc(v_uid) || jsonb_build_object('allowed', true, 'reason', null, 'counted', false);   -- 이미 시작한 면접은 끝까지
  end if;
  st := public.ai_usage_calc(v_uid);
  if (st->>'admin')::boolean then return st; end if;
  if not (st->>'allowed')::boolean then return st || jsonb_build_object('counted', false); end if;
  insert into public.ai_usage (user_id, interview_id) values (v_uid, v_iid) on conflict (user_id, interview_id) do nothing;
  return public.ai_usage_calc(v_uid) || jsonb_build_object('allowed', true, 'reason', null, 'counted', true);
end $$;
revoke all on function public.ai_usage_try(text) from public, anon;
grant execute on function public.ai_usage_try(text) to authenticated;

-- 본인 남은 횟수 보기 (세지 않음)
create or replace function public.ai_usage_status()
returns jsonb language sql stable security definer set search_path = public as $$
  select case when auth.uid() is null then jsonb_build_object('allowed', false, 'reason', 'login')
              else public.ai_usage_calc(auth.uid()) end;
$$;
revoke all on function public.ai_usage_status() from public, anon;
grant execute on function public.ai_usage_status() to authenticated;

-- 관리자 화면: 사람별 오늘·전체 사용 횟수 (관리자·교직원은 모두, 학과 담당은 맡은 학생만, 그 밖에는 빈 목록)
create or replace function public.ai_usage_admin_summary()
returns table (user_id uuid, used_today integer, used_total integer, last_used_at timestamptz)
language sql stable security definer set search_path = public as $$
  select u.user_id,
         (count(*) filter (where u.used_on = (now() at time zone 'Asia/Seoul')::date))::int,
         count(*)::int,
         max(u.used_at)
    from public.ai_usage u
   where public.can_see_user(u.user_id)
   group by u.user_id;
$$;
revoke all on function public.ai_usage_admin_summary() from public, anon;
grant execute on function public.ai_usage_admin_summary() to authenticated;

-- 관리자: 한 사람의 AI 면접 사용 기록을 모두 지움 (지운 줄 수를 돌려줌)
create or replace function public.ai_usage_reset(p_user uuid)
returns integer language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if not public.is_admin() then raise exception 'AI 사용 기록은 관리자만 지울 수 있어요'; end if;
  delete from public.ai_usage where user_id = p_user;
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.ai_usage_reset(uuid) from public, anon;
grant execute on function public.ai_usage_reset(uuid) to authenticated;

