-- 이번 달(한국 시간 1일 0시부터) 면접 중 타입캐스트로 읽은 크레딧 (회사 전체) → tts_guard.month_cap과 비교
create or replace function public.tts_live_month_used()
returns bigint language sql stable security definer set search_path = public as $$
  select coalesce(sum(chars), 0)::bigint from public.tts_usage
   where kind = 'live' and provider = 'typecast'
     and created_at >= (date_trunc('month', now() at time zone 'Asia/Seoul') at time zone 'Asia/Seoul');
$$;
-- 이번 달 한 사람이 면접 중 타입캐스트로 쓴 크레딧 (관리자 시험 읽기 admin_test는 뺌) → 1인 한도와 비교
create or replace function public.tts_user_month_used(p_user uuid)
returns bigint language sql stable security definer set search_path = public as $$
  select coalesce(sum(chars), 0)::bigint from public.tts_usage
   where user_id = p_user and kind = 'live' and provider = 'typecast'
     and purpose is distinct from 'admin_test'
     and created_at >= (date_trunc('month', now() at time zone 'Asia/Seoul') at time zone 'Asia/Seoul');
$$;
-- speak-text가 서버 키로만 부름
revoke all on function public.tts_live_month_used() from public, anon, authenticated;
revoke all on function public.tts_user_month_used(uuid) from public, anon, authenticated;
grant execute on function public.tts_live_month_used() to service_role;
grant execute on function public.tts_user_month_used(uuid) to service_role;

