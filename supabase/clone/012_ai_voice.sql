--  tts_usage              : 타입캐스트·OpenAI 목소리 사용 기록     ← speak-text(live), typecast-tts(preview), generate-audio(record)가 서버 키로 남김
--                           앱: 관리자 '타입캐스트 크레딧'·'즉석으로 읽은 문장'
--  tts_live_month_used()  : 이번 달(한국 시간) 면접 중 타입캐스트 사용량 (회사 전체) ← speak-text 안전장치 (서버 키로 부름)
--  tts_user_month_used()  : 이번 달 한 사람의 타입캐스트 사용량    ← speak-text 1인 한도 (서버 키로 부름)
