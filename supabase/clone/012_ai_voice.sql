-- intro-coach가 대본을 만들기 전에 부름 (p_limit = 하루 횟수, 함수는 10을 보냄. 1~50 사이로 맞춤). 관리자는 한도 없음
--   돌려주는 값: {allowed, admin, used, limit, left}
create or replace function public.intro_coach_try(p_limit integer default 10)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_lim int := least(greatest(coalesce(p_limit, 10), 1), 50); v_used int;
begin
  if v_uid is null then return jsonb_build_object('allowed', false, 'reason', 'login'); end if;
  if public.is_admin() then return jsonb_build_object('allowed', true, 'admin', true); end if;
  perform pg_advisory_xact_lock(hashtext('ai_coach:' || v_uid::text));
  select count(*) into v_used from public.ai_coach_usage where user_id = v_uid and used_on = (now() at time zone 'Asia/Seoul')::date;
  if v_used >= v_lim then
    return jsonb_build_object('allowed', false, 'admin', false, 'reason', 'daily', 'used', v_used, 'limit', v_lim, 'left', 0);
  end if;
  insert into public.ai_coach_usage (user_id) values (v_uid);
  return jsonb_build_object('allowed', true, 'admin', false, 'used', v_used + 1, 'limit', v_lim, 'left', v_lim - v_used - 1);
end $$;
revoke all on function public.intro_coach_try(integer) from public, anon;
grant execute on function public.intro_coach_try(integer) to authenticated;

-- ── 목소리 사용 기록 ──
--   kind     : live(면접 중 즉석으로 읽음) | record(질문·문장 녹음) | preview(관리자 미리 듣기)
