--  app_settings 기본값    : ai_limits(하루·전체 횟수), tts_guard(크레딧 안전장치), ai_followup·ai_grading(AI 켜기, 기본 꺼짐)
--  저장소 question-audio  : 녹음 mp3(q/, l/)와 면접관 사진(persona/). 누구나 읽기, 쓰기는 관리자(서버 함수는 서버 키로 씀)
