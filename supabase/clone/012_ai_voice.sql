-- 질문 내용(질문·읽기용 문장·힌트·모범답안)이 바뀔 때만 수정 시각을 남김 (녹음 파일만 바뀐 것은 수정으로 치지 않음)
create or replace function public.questions_touch() returns trigger
language plpgsql set search_path = public as $$
begin
  if (new.q, new.q_spoken, new.hint, new.ref) is distinct from (old.q, old.q_spoken, old.hint, old.ref) then
    new.updated_at := now();
    new.updated_by := coalesce(auth.uid(), new.updated_by);
  end if;
  return new;
end $$;
drop trigger if exists questions_touch on public.questions;
create trigger questions_touch before update on public.questions for each row execute function public.questions_touch();

