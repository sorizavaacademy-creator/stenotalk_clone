-- 면접관 10명(인사팀장·현업 팀장·…·공공·청렴형)마다 어떤 목소리를 쓸지 관리자가 그때그때 바꾸는 표
--   persona_id : 앱의 면접관 id (hr, lead, exec, senior, press, data, value, logic, quiet, ethics)
--   provider   : typecast | openai | browser   (지금 클론은 타입캐스트 API가 없어 browser로 미리 듣기)
--   voice_id / voice_name / voice_meta : 타입캐스트 목소리 (voice_meta = 성별·나이 등 목록에서 받은 정보)
--   tempo, pitch : 속도(0.5~2배), 높낮이(-12~12)
--   emotions   : 상황별 감정 {"question":"normal","followup":"calm","press":"toneup"}
--   fallback   : 타입캐스트가 안 될 때 (openai | browser | text)
--   version    : 소리(목소리·속도·높낮이·감정)가 바뀔 때만 1씩 늘어남 → 녹음본을 이 버전(목소리 서명)별로 따로 보관할 때 씀
-- 학생 화면은 읽기만(면접 시작 때 설정을 고정해 씀). 쓰기는 관리자만 set_interviewer_voices()로, 바꿀 때마다 기록이 남음

create table if not exists public.interviewer_voices (
  persona_id text primary key check (persona_id ~ '^[a-z]{2,20}$'),
  provider text not null default 'typecast' check (provider in ('typecast','openai','browser')),
  voice_id text,
  voice_name text,
  voice_meta jsonb not null default '{}'::jsonb,
  tempo numeric(3,2) not null default 1 check (tempo between 0.5 and 2),
  pitch integer not null default 0 check (pitch between -12 and 12),
  emotions jsonb not null default '{"question":"normal","followup":"normal","press":"normal"}'::jsonb,
  fallback text not null default 'browser' check (fallback in ('openai','browser','text')),
  enabled boolean not null default true,
  version integer not null default 1,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);
alter table public.interviewer_voices enable row level security;
drop policy if exists "interviewer_voices: 로그인하면 읽기" on public.interviewer_voices;
create policy "interviewer_voices: 로그인하면 읽기" on public.interviewer_voices for select to authenticated using (true);

create table if not exists public.interviewer_voice_log (
  id bigint generated by default as identity primary key,
  persona_id text not null,
  before jsonb,
  after jsonb,
  note text,
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists interviewer_voice_log_idx on public.interviewer_voice_log (created_at desc);
alter table public.interviewer_voice_log enable row level security;
drop policy if exists "interviewer_voice_log: 관리자 읽기" on public.interviewer_voice_log;
create policy "interviewer_voice_log: 관리자 읽기" on public.interviewer_voice_log for select to authenticated using (public.is_admin());

-- 여러 면접관을 한 번에 저장 (바뀐 것만 버전을 올리고 기록)
create or replace function public.set_interviewer_voices(p_rows jsonb, p_note text default null) returns integer
language plpgsql security definer set search_path = public as $$
declare r jsonb; pid text; b jsonb; a jsonb; n int := 0;
begin
  if not public.is_admin() then raise exception '면접관 목소리는 관리자만 바꿀 수 있어요'; end if;
  if jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) > 20 then raise exception '잘못된 요청이에요'; end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    pid := r->>'persona_id';
    select to_jsonb(v) - 'updated_at' - 'updated_by' - 'version' into b from public.interviewer_voices v where persona_id = pid;
    insert into public.interviewer_voices as v (persona_id, provider, voice_id, voice_name, voice_meta, tempo, pitch, emotions, fallback, enabled, updated_by, updated_at)
    values (pid, coalesce(r->>'provider','typecast'), nullif(r->>'voice_id',''), nullif(r->>'voice_name',''), coalesce(r->'voice_meta','{}'::jsonb),
            coalesce((r->>'tempo')::numeric, 1), coalesce((r->>'pitch')::int, 0),
            coalesce(r->'emotions','{"question":"normal","followup":"normal","press":"normal"}'::jsonb), coalesce(r->>'fallback','browser'),
            coalesce((r->>'enabled')::boolean, true), auth.uid(), now())
    on conflict (persona_id) do update set provider = excluded.provider, voice_id = excluded.voice_id, voice_name = excluded.voice_name,
      voice_meta = excluded.voice_meta, tempo = excluded.tempo, pitch = excluded.pitch, emotions = excluded.emotions, fallback = excluded.fallback,
      enabled = excluded.enabled, updated_by = auth.uid(), updated_at = now(),
      version = v.version + case when (v.provider, v.voice_id, v.tempo, v.pitch, v.emotions) is distinct from (excluded.provider, excluded.voice_id, excluded.tempo, excluded.pitch, excluded.emotions) then 1 else 0 end;   -- 소리가 바뀔 때만 (녹음본 다시 만들 기준)
    select to_jsonb(v) - 'updated_at' - 'updated_by' - 'version' into a from public.interviewer_voices v where persona_id = pid;
    if b is distinct from a then
      insert into public.interviewer_voice_log (persona_id, before, after, note, changed_by) values (pid, b, a, nullif(trim(p_note), ''), auth.uid());
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;
revoke all on function public.set_interviewer_voices(jsonb, text) from public, anon;
grant execute on function public.set_interviewer_voices(jsonb, text) to authenticated;
