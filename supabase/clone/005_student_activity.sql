-- ── 면접 결과 ──
create table if not exists public.interview_records (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  field_id text not null,
  field_name text not null,
  score integer,
  question_count integer,
  duration_label text,
  created_at timestamptz not null default now(),
  mode text not null default 'classic',
  set_kind text,
  set_overtime boolean,
  set_review jsonb,
  nonverbal jsonb
);
create index if not exists interview_records_user_idx on public.interview_records (user_id, created_at desc);

create table if not exists public.interview_answers (
  id uuid primary key default gen_random_uuid(),
  record_id uuid not null references public.interview_records(id) on delete cascade,
  question_index integer not null,
  question_text text not null,
  answer_text text default '',
  score integer,
  created_at timestamptz not null default now(),
  feedback text,
  kind text not null default 'question',
  answer_raw text,
  answer_fixed_at timestamptz
);
create index if not exists interview_answers_record_idx on public.interview_answers (record_id, question_index);

alter table public.interview_records enable row level security;
alter table public.interview_answers enable row level security;
create policy "interview_records: 본인 만들기" on public.interview_records for insert to authenticated with check (user_id = auth.uid());
create policy "interview_records: 본인 읽기" on public.interview_records for select to authenticated using (user_id = auth.uid());
create policy "interview_records: 관리자 읽기" on public.interview_records for select to authenticated using (public.is_admin());
create policy "interview_records: 관리자 지우기" on public.interview_records for delete to authenticated using (public.is_admin());
create policy "interview_answers: 본인 기록에 넣기" on public.interview_answers for insert to authenticated
  with check (exists (select 1 from public.interview_records r where r.id = record_id and r.user_id = auth.uid()));
create policy "interview_answers: 본인 읽기" on public.interview_answers for select to authenticated
  using (exists (select 1 from public.interview_records r where r.id = record_id and r.user_id = auth.uid()));
create policy "interview_answers: 관리자 읽기·고치기" on public.interview_answers for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- 실전 세트 면접관 종합 의견 저장 (본인 기록에만)
create or replace function public.save_set_review(p_record_id uuid, p_review jsonb) returns void
language sql security definer set search_path = public as $$
  update public.interview_records set set_review = p_review where id = p_record_id and user_id = auth.uid();
$$;
revoke all on function public.save_set_review(uuid, jsonb) from public, anon;
grant execute on function public.save_set_review(uuid, jsonb) to authenticated;

