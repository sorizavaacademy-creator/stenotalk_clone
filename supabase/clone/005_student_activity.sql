-- 답장을 읽었다고 표시 (본인 글만)
create or replace function public.feedback_reply_seen(p_ids bigint[]) returns void
language sql security definer set search_path = public as $$
  update public.feedback set reply_seen_at = now() where id = any(p_ids) and user_id = auth.uid() and replied_at is not null and reply_seen_at is null;
$$;
revoke all on function public.feedback_reply_seen(bigint[]) from public, anon;
grant execute on function public.feedback_reply_seen(bigint[]) to authenticated;

